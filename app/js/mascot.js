/** 2 枚を重ねる（上の絵の '#' を優先） */
const over = (base, top, dy = 0) => base.map((row, y) => row.split('').map((c, x) => (top[y - dy]?.[x] === '#' ? '#' : c)).join(''));
const shift = (art, dy) => art.map((_, y) => art[y - dy] || '............');

export const MASCOTS = [
  { name: 'たまご', art: EGG },
  { name: '子犬', art: PUPPY },
  { name: '若犬', art: YOUNG },
  { name: '成犬', art: ADULT },
  { name: '名犬', art: over(shift(ADULT, 1), STAR) },
  { name: 'ポポ級', art: over(shift(ADULT, 2), CROWN) },
];

/** 段階 index → SVG 文字列（色は currentColor） */
export function mascotSvg(stageIndex, size = 48) {
  const m = MASCOTS[Math.max(0, Math.min(MASCOTS.length - 1, stageIndex))];
  const rects = [];
  m.art.forEach((row, y) => { for (let x = 0; x < row.length; x++) if (row[x] === '#') rects.push(`<rect x="${x}" y="${y}" width="1" height="1"/>`); });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" width="${size}" height="${size}" shape-rendering="crispEdges" fill="currentColor" role="img" aria-label="${m.name}">${rects.join('')}</svg>`;
}
